    def test_two_new_apps_from_the_same_main_both_merge(self):
        """The second PR was opened before the first merged: it registers no other unit and holds the egress
        port the first now has. Main's tooling makes the registry and the port again; the PR still merges."""
        (self.root / egress.PROXY_FILE).parent.mkdir(parents=True)
