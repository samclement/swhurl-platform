"""Notification channels and which team's apps notify them (docs/services.md#notification-channels).

A channel is a named destination: one SOPS-encrypted Secret in platform/notify whose address is the
credential (an ntfy topic URL). Its name and transport are plain metadata; the address is written once
and never shown again. A team names the one channel its apps notify in apps/teams.yaml; that reaches
the cluster as the generated ROUTES_FILE, which the notification checker reads.

Reads and rendering only (PyYAML): the app policy imports this. The commands are in teams.py.
"""
from __future__ import annotations

import json
from pathlib import Path
from urllib.parse import urlsplit

from swhurl import interface, yamlio
from swhurl.apps.contract import TEAMS_FILE
from swhurl.apps.model import generated, records

NOTIFY_DIR = Path('platform/notify')
ROUTES_FILE = NOTIFY_DIR / 'routes.yaml'
UNIT_FILE = Path('clusters/home/platform-notify.yaml')
NAMESPACE = 'notify'
ROUTES_NAME = 'notification-routes'
ROUTES_KEY = 'routes.json'
SECRET_PREFIX = 'channel-'
ADDRESS_KEY = 'address'
TRANSPORT = interface.label('notify-transport')
TRANSPORTS = ('ntfy',)


def channel_file(name: str) -> Path:
    return NOTIFY_DIR / f'{SECRET_PREFIX}{name}.sops.yaml'


def address_problem(transport: str, address: str) -> str | None:
    """Why ``address`` cannot be a channel of ``transport``; the message never repeats the address."""
    if transport not in TRANSPORTS:
        return f'unknown transport {transport!r}; supported: {", ".join(TRANSPORTS)}'
    parts = urlsplit(address)
    topic = parts.path.strip('/')
    if (parts.scheme != 'https' or not parts.netloc or not topic or '/' in topic
            or parts.query or parts.fragment or parts.username or parts.password):
        return 'an ntfy address is an HTTPS topic URL without a query or fragment, such as https://ntfy.sh/<topic>'
    return None


def channels(root: Path) -> dict[str, str]:
    """Each channel in Git with its transport, read from the Secrets' plain metadata (nothing is decrypted)."""
    found = {}
    for path in sorted((root / NOTIFY_DIR).glob(f'{SECRET_PREFIX}*.sops.yaml')):
        metadata = (yamlio.load(path.read_text()) or {}).get('metadata') or {}
        name = str(metadata.get('name', '')).removeprefix(SECRET_PREFIX)
        found[name] = (metadata.get('labels') or {}).get(TRANSPORT, '')
    return found


def team_channels(root: Path) -> dict[str, list[str]]:
    """The channels each team's apps notify, for the teams that name any."""
    path = root / TEAMS_FILE
    registered = (yamlio.load(path.read_text()) or {}).get('teams') or {} if path.is_file() else {}
    return {team: list(entry['notify']) for team, entry in registered.items() if (entry or {}).get('notify')}


def routes(root: Path) -> dict:
    """What the cluster is told: each channel with its transport, and each team's channels. No address."""
    return {'channels': channels(root), 'teams': team_channels(root)}


def routes_configmap(wanted: dict) -> str:
    routes = json.dumps(wanted, indent=2, sort_keys=True)
    return ('# Generated by make channel-add, make channel-remove, make team-edit and make app-sync from the channel\n'
            '# files here and apps/teams.yaml: do not edit. Names only; each address is in its own encrypted Secret.\n'
            'apiVersion: v1\nkind: ConfigMap\nmetadata:\n'
            f'  name: {ROUTES_NAME}\n  namespace: {NAMESPACE}\n'
            f'data:\n  {ROUTES_KEY}: |\n' + ''.join(f'    {line}\n' for line in routes.splitlines()))


def routes_file(root: Path) -> tuple[Path, str] | None:
    """The routes as they should be on disk, with their path; None where this root has no notify unit
    (the scratch roots of tests and template checks)."""
    if not (root / NOTIFY_DIR).is_dir():
        return None
    return root / ROUTES_FILE, routes_configmap(routes(root))


def problems(root: Path) -> list[str]:
    """Why the channels, the teams that name them and the generated routes disagree (rule notify-channels)."""
    if not (root / NOTIFY_DIR).is_dir():
        return []
    found = []
    known = channels(root)
    listed = (yamlio.load((root / NOTIFY_DIR / 'kustomization.yaml').read_text()) or {}).get('resources') or []
    for name, transport in known.items():
        if not records.NAME_RE.match(name) or transport not in TRANSPORTS:
            found.append(f'{channel_file(name)} is not a channel Secret named {SECRET_PREFIX}<name> with a supported '
                         f'{TRANSPORT} label ({", ".join(TRANSPORTS)})')
        if channel_file(name).name not in listed:
            found.append(f'{channel_file(name).name} is not in {NOTIFY_DIR}/kustomization.yaml: the channel would not exist')
    for team, names in team_channels(root).items():
        if len(names) > 1:
            found.append(f'team {team} notifies {len(names)} channels; a team has one (make team-edit NAME={team} ARGS="--notify <channel>")')
        missing = [name for name in names if name not in known]
        if missing:
            found.append(f'team {team} notifies {", ".join(missing)}, which is not a channel (make channel-add)')
    unit = root / UNIT_FILE
    encrypted = any((root / NOTIFY_DIR).glob('*.sops.yaml'))
    if unit.is_file() and ('decryption' in (yamlio.load(unit.read_text()).get('spec') or {})) != encrypted:
        found.append(f'{UNIT_FILE} must decrypt exactly while {NOTIFY_DIR} holds an encrypted file (the channel commands set it)')
    if not generated.same(*routes_file(root)):
        found.append(f'{ROUTES_FILE} is not what the channel files and apps/teams.yaml declare; make app-sync rewrites it')
    return [f'notify-channels: {problem}' for problem in found]
