// A change and its publication: what a kind's pull request carries, and the one commit and pull request that ask for
// it. The seven steps around this use case — resolve main, extract it, apply the change, read the tree back — are a
// command's; what is decided here is what may be carried, in which order it is written, and what the operator is told,
// so a change and the page that follows it cannot disagree about either.

// PublishInputs is one change ready to publish: the tree before and after it was applied, and who asked for it.
type PublishInputs struct {
	Change     pages.ConsoleChange
	Name, Env  string
	Identity   string // who requested it, as the pull request's trailer states it
	Revision   string // the commit the change was applied to, which the branch and the commit name
	Before     []files.TreeFile
	After      []files.TreeFile
	Commands   []string // the commands as the operator would type them, for the pull request's body
	Preface    string   // what the body says before those commands: a creation names the repository and template it made
	Repository string
	Token      string
	DryRun     bool // decide and report, and write nothing to GitHub
}

// Published is what one change carried: its branch, the paths and the letter each one got, and the pull request the
// last line of the operator's output names.
type Published struct {
	Branch string
	Paths  []string
	Status map[string]string // path → "A" (added), "M" (modified) or "D" (deleted)
	URL    string
}

// Publish creates the change's one commit on its own branch and the pull request that asks for it, reporting each
// step as it goes. A change that carries no file is refused before anything is written, and a dry run writes nothing.
func Publish(ctx context.Context, inputs PublishInputs, publisher github.Publisher, note func(string)) (Published, error) {
	branch, err := inputs.Change.Branch(inputs.Name, inputs.Env, shortRevision(inputs.Revision))
	if err != nil {
		return Published{}, err
	}
	before, after := treeOf(inputs.Before), treeOf(inputs.After)
	paths, status := carried(inputs.Change, inputs.Name, inputs.Env, before, after)
	if len(paths) == 0 {
		return Published{}, &Refusal{"change", "the change left no files changed; nothing to propose"}
	}
	for _, path := range paths {
		note(status[path] + " " + path)
	}
	plan := pages.MergePlanFor(inputs.Change.Name, changedPaths(paths, status))
	note("Merge plan: you merge it on GitHub" + planLine(plan))
	body := inputs.Preface + "Generated by the console with:\n\n    " + strings.Join(inputs.Commands, " && ")
	published := Published{Branch: branch, Paths: paths, Status: status}
	if inputs.DryRun {
		note(fmt.Sprintf("Dry run: would commit %d file(s) to %s; no PR opened", len(paths), branch))
		return published, nil
	}
	url, err := publishCommit(ctx, inputs, publisher, note, branch, body, paths, status, before, after, plan)
	if err != nil {
		return Published{}, err
	}
	published.URL = url
	return published, nil
}

// publishCommit writes the files, the tree, the commit, the branch and the pull request, in that order.
func publishCommit(ctx context.Context, inputs PublishInputs, publisher github.Publisher, note func(string),
	branch, body string, paths []string, status map[string]string, before, after map[string]files.TreeFile,
	plan string) (string, error) {
	base, err := publisher.BaseTree(ctx, inputs.Repository, inputs.Token, inputs.Revision)
	if err != nil {
		return "", err
	}
	entries := make([]github.TreeEntry, 0, len(paths))
	for _, path := range paths {
		if status[path] == "D" {
			entries = append(entries, github.TreeEntry{Path: path, Mode: modeOf(before[path])})
			continue
		}
		blob, err := publisher.Blob(ctx, inputs.Repository, inputs.Token, after[path].Body)
		if err != nil {
			return "", err
		}
		entries = append(entries, github.TreeEntry{Path: path, Mode: modeOf(after[path]), SHA: blob})
	}
	tree, err := publisher.Tree(ctx, inputs.Repository, inputs.Token, base, entries)
	if err != nil {
		return "", err
	}
	title := inputs.Change.Heading(inputs.Name, inputs.Env)
	commit, err := publisher.Commit(ctx, inputs.Repository, inputs.Token, github.NewCommit{
		Message: "[console] " + title + "\n\n" + body + "\n\nRequested-by: " + inputs.Identity + "\n",
		Tree:    tree, Parent: inputs.Revision, Author: consoleAuthor})
	if err != nil {
		return "", err
	}
	note("Committed " + shortRevision(commit) + " [console] " + title)
	note("Creating branch " + branch)
	if err := publisher.Branch(ctx, inputs.Repository, inputs.Token, branch, commit); err != nil {
		return "", err
	}
	pull, err := publisher.OpenPull(ctx, inputs.Repository, inputs.Token, github.NewPull{
		Title: "[console] " + title, Head: branch, Base: "main",
		Body: body + planSuffix(plan) + "\n\nRequested-by: " + inputs.Identity})
	if err != nil {
		return "", err
	}
	note("Opened " + pull.URL)
	return pull.URL, nil
}

// consoleAuthor is who a console commit is authored by: the console itself, never the person who asked for it, whose
// identity the message's trailer states.
var consoleAuthor = github.Signature{Name: "swhurl console", Email: "console@users.noreply.github.com"}

// planLine is what the operator is told about merging, as the job's output states it.
func planLine(plan string) string {
	if plan == "" {
		return ""
	}
	return "; it " + plan
}

// planSuffix is the pull request's merge-plan sentence, or nothing when merging is all it needs.
func planSuffix(plan string) string {
	if plan == "" {
		return ""
	}
	return "\n\n**Merge plan:** it " + plan + "."
}

// treeOf indexes one state of the tree by path.
func treeOf(tree []files.TreeFile) map[string]files.TreeFile {
	found := make(map[string]files.TreeFile, len(tree))
	for _, file := range tree {
		found[file.Path] = file
	}
	return found
}

// carried is the paths the change keeps, in path order, and the letter each one gets. A path the kind does not own
// is dropped, so a change cannot carry a file it did not derive — another app's record, or one of the operator's own.
func carried(change pages.ConsoleChange, name, env string, before, after map[string]files.TreeFile) ([]string, map[string]string) {
	status := differences(before, after)
	kept := make([]string, 0, len(status))
	for path := range status {
		if change.Owns(name, env, path) {
			kept = append(kept, path)
		}
	}
	slices.Sort(kept)
	return kept, status
}

// differences is the letter every path of the two states gets: added, modified (its bytes or its mode), or deleted.
// An unchanged path is absent from the answer.
func differences(before, after map[string]files.TreeFile) map[string]string {
	found := map[string]string{}
	for path, file := range after {
		was, had := before[path]
		switch {
		case !had:
			found[path] = "A"
		case was.Executable != file.Executable || !bytes.Equal(was.Body, file.Body):
			found[path] = "M"
		}
	}
	for path := range before {
		if _, remains := after[path]; !remains {
			found[path] = "D"
		}
	}
	return found
}

// changedPaths is the paths a change added or modified: what its merge plan is read from, since a deletion needs no
// value set.
func changedPaths(paths []string, status map[string]string) []string {
	kept := make([]string, 0, len(paths))
	for _, path := range paths {
		if status[path] != "D" {
			kept = append(kept, path)
		}
	}
	return kept
}

// modeOf is a file's repository mode.
func modeOf(file files.TreeFile) string {
	if file.Executable {
		return "100755"
	}
	return "100644"
}

// shortRevision is the seven characters a branch and a line name a commit by.
func shortRevision(revision string) string {
	if len(revision) > 7 {
		return revision[:7]
	}
	return revision
}
