const publishRevision = "0123456789abcdef0123456789abcdef01234567"

// published builds one change of a scale on web/staging whose record and unit changed, one shared file changed, and
// one file of another app that must not travel.
func published(t *testing.T) (orchestration.PublishInputs, *githubtest.PublisherFake, *[]string) {
	t.Helper()
	change, found := pages.ConsoleChangeNamed("v2-scale")
	if !found {
		t.Fatal("v2-scale is not a kind")
	}
	before := []files.TreeFile{
		{Path: "v2-records/web/staging/instance.json", Body: []byte(`{"replicas":1}`)},
		{Path: "v2-records/calls.json", Body: []byte(`{"calls":[]}`)},
		{Path: "v2-records/other/staging/instance.json", Body: []byte(`{"replicas":1}`)},
		{Path: "v2-apps/instances/web/staging/kustomization.yaml", Body: []byte("resources:\n")},
		{Path: "v2-check.sh", Executable: true, Body: []byte("#!/bin/sh\n")},
		{Path: "v2-records/web/staging/old.json", Body: []byte("old\n")},
	}
	after := []files.TreeFile{
		{Path: "v2-records/web/staging/instance.json", Body: []byte(`{"replicas":3}`)},
		{Path: "v2-records/calls.json", Body: []byte(`{"calls":["orders"]}`)},
		{Path: "v2-records/other/staging/instance.json", Body: []byte(`{"replicas":2}`)},
		{Path: "v2-apps/instances/web/staging/kustomization.yaml", Body: []byte("resources:\n- helmrelease.json\n")},
		{Path: "v2-check.sh", Executable: true, Body: []byte("#!/bin/sh\n")},
	}
	inputs := orchestration.PublishInputs{Change: change, Name: "web", Env: "staging",
		Identity: "operator@example.test", Revision: publishRevision, Before: before, After: after,
		Commands:   []string{"swhurl-v2 edit --records v2-records --app web --env=staging --set replicas=3", "swhurl-v2 render --records v2-records --revision @base"},
		Repository: "owner/repo", Token: "token"}
	publisher := githubtest.NewPublisher(githubtest.PublisherScenario())
	lines := &[]string{}
	return inputs, publisher, lines
}

// A change carries only what its kind owns, in path order, with the letter each path gets, and says so as it goes.
func TestPublishCarriesOnlyItsOwnPaths(t *testing.T) {
	inputs, publisher, lines := published(t)
	got, err := orchestration.Publish(context.Background(), inputs, publisher,
		func(line string) { *lines = append(*lines, line) })
	if err != nil {
		t.Fatal(err)
	}
	want := []string{"v2-apps/instances/web/staging/kustomization.yaml", "v2-records/calls.json",
		"v2-records/web/staging/instance.json", "v2-records/web/staging/old.json"}
	if strings.Join(got.Paths, ",") != strings.Join(want, ",") {
		t.Fatalf("paths = %v, want %v", got.Paths, want)
	}
	wantStatus := map[string]string{"v2-apps/instances/web/staging/kustomization.yaml": "M",
		"v2-records/calls.json": "M", "v2-records/web/staging/instance.json": "M",
		"v2-records/web/staging/old.json": "D"}
	for path, letter := range wantStatus {
		if got.Status[path] != letter {
			t.Errorf("%s = %q, want %q", path, got.Status[path], letter)
		}
	}
	if got.Branch != "console/v2-scale-web-staging-0123456" {
		t.Errorf("branch = %q", got.Branch)
	}
	if got.URL != githubtest.PublisherScenario().PullURL {
		t.Errorf("url = %q", got.URL)
	}
	wantLines := []string{
		"M v2-apps/instances/web/staging/kustomization.yaml",
		"M v2-records/calls.json",
		"M v2-records/web/staging/instance.json",
		"D v2-records/web/staging/old.json",
		"Merge plan: you merge it on GitHub",
		"Committed 3333333 [console] apps: scale web/staging",
		"Creating branch console/v2-scale-web-staging-0123456",
		"Opened " + githubtest.PublisherScenario().PullURL,
	}
	if strings.Join(*lines, "\n") != strings.Join(wantLines, "\n") {
		t.Errorf("lines:\n%s\nwant:\n%s", strings.Join(*lines, "\n"), strings.Join(wantLines, "\n"))
	}
}

// The one commit says what the console said before this slice: its title, the commands a person can type, the
// requester's trailer, and the console as author; the pull request repeats the body and adds the merge plan.
func TestPublishCommitAndPullRequestBody(t *testing.T) {
	inputs, publisher, _ := published(t)
	if _, err := orchestration.Publish(context.Background(), inputs, publisher, func(string) {}); err != nil {
		t.Fatal(err)
	}
	if len(publisher.Commits) != 1 || len(publisher.Pulls) != 1 || len(publisher.Refs) != 1 {
		t.Fatalf("wrote %d commits, %d pulls, %d refs", len(publisher.Commits), len(publisher.Pulls), len(publisher.Refs))
	}
	body := "Generated by the console with:\n\n    " + strings.Join(inputs.Commands, " && ")
	want := "[console] apps: scale web/staging\n\n" + body + "\n\nRequested-by: operator@example.test\n"
	if publisher.Commits[0].Message != want {
		t.Errorf("commit message:\n%s\nwant:\n%s", publisher.Commits[0].Message, want)
	}
	if publisher.Commits[0].Author != (github.Signature{Name: "swhurl console",
		Email: "console@users.noreply.github.com"}) {
		t.Errorf("author = %#v", publisher.Commits[0].Author)
	}
	if publisher.Commits[0].Parent != publishRevision || publisher.Commits[0].Tree != githubtest.PublisherScenario().Tree {
		t.Errorf("commit = %#v", publisher.Commits[0])
	}
	if wantPull := body + "\n\nRequested-by: operator@example.test"; publisher.Pulls[0].Body != wantPull {
		t.Errorf("pull body:\n%s\nwant:\n%s", publisher.Pulls[0].Body, wantPull)
	}
	if publisher.Pulls[0].Title != "[console] apps: scale web/staging" || publisher.Pulls[0].Base != "main" ||
		publisher.Pulls[0].Head != "console/v2-scale-web-staging-0123456" {
		t.Errorf("pull = %#v", publisher.Pulls[0])
	}
	if publisher.Refs[0].Name != "console/v2-scale-web-staging-0123456" ||
		publisher.Refs[0].Commit != githubtest.PublisherScenario().Commit {
		t.Errorf("ref = %#v", publisher.Refs[0])
	}
	// the blobs are the modified files' bytes, and a deletion names the mode the file had
	entries := publisher.Trees[0].Entries
	for _, entry := range entries {
		if entry.Path == "v2-records/web/staging/old.json" && (entry.SHA != "" || entry.Mode != "100644") {
			t.Errorf("a deletion = %#v", entry)
		}
		if entry.Path == "v2-records/calls.json" && entry.SHA != githubtest.PublisherScenario().Blob {
			t.Errorf("a written entry = %#v", entry)
		}
	}
	if len(publisher.Blobs) != 3 {
		t.Errorf("%d blobs: a deletion uploads nothing", len(publisher.Blobs))
	}
}

// An executable's mode travels with it, and a change that only changes a mode is still a change.
func TestPublishKeepsModes(t *testing.T) {
	inputs, publisher, lines := published(t)
	inputs.Change, _ = pages.ConsoleChangeNamed("v2-team")
	inputs.Before = append(inputs.Before, files.TreeFile{Path: "v2-records/web/prod/run.sh", Executable: true,
		Body: []byte("#!/bin/sh\n")})
	inputs.After = append(inputs.After, files.TreeFile{Path: "v2-records/web/prod/run.sh", Body: []byte("#!/bin/sh\n")})
	got, err := orchestration.Publish(context.Background(), inputs, publisher, func(line string) {
		*lines = append(*lines, line)
	})
	if err != nil {
		t.Fatal(err)
	}
	if got.Status["v2-records/web/prod/run.sh"] != "M" {
		t.Errorf("a lost mode is not a change: %v", got.Status)
	}
	for _, entry := range publisher.Trees[0].Entries {
		if entry.Path == "v2-records/web/prod/run.sh" && entry.Mode != "100644" {
			t.Errorf("the new mode is not the file's: %#v", entry)
		}
	}
}

// A change that carries nothing is refused before GitHub is written, and a dry run writes nothing at all.
func TestPublishWritesNothingWhenItShouldNot(t *testing.T) {
	inputs, publisher, lines := published(t)
	unchanged := orchestrator(inputs)
	unchanged.After = unchanged.Before
	if _, err := orchestration.Publish(context.Background(), unchanged, publisher, func(string) {}); err == nil {
		t.Error("a change that carries no file was published")
	}
	if len(publisher.Blobs)+len(publisher.Trees)+len(publisher.Commits)+len(publisher.Refs)+len(publisher.Pulls) != 0 {
		t.Error("a refused change wrote to GitHub")
	}
	dry := orchestrator(inputs)
	dry.DryRun = true
	got, err := orchestration.Publish(context.Background(), dry, publisher, func(line string) {
		*lines = append(*lines, line)
	})
	if err != nil {
		t.Fatal(err)
	}
	if got.URL != "" || len(publisher.Blobs)+len(publisher.Pulls) != 0 {
		t.Error("a dry run wrote to GitHub")
	}
	last := (*lines)[len(*lines)-1]
	if last != "Dry run: would commit 4 file(s) to console/v2-scale-web-staging-0123456; no PR opened" {
		t.Errorf("last line = %q", last)
	}
}

// orchestrator is published's inputs without its shared fixture, so a test can change one field.
func orchestrator(inputs orchestration.PublishInputs) orchestration.PublishInputs {
	before := append([]files.TreeFile(nil), inputs.Before...)
	after := append([]files.TreeFile(nil), inputs.After...)
	inputs.Before, inputs.After = before, after
	return inputs
}

// A team's change is the registry's and its channel's, and its merge plan needs the Secret's values set on the branch.
func TestPublishTeamChannel(t *testing.T) {
	change, _ := pages.ConsoleChangeNamed("team-channel-set")
	inputs := orchestration.PublishInputs{Change: change, Name: "payments", Identity: "operator@example.test",
		Revision: publishRevision, Repository: "owner/repo", Token: "token",
		Commands: []string{"swhurl-v2 team --records v2-records --team payments --action channel"},
		Before: []files.TreeFile{{Path: "v2-records/teams.json", Body: []byte(`{}`)},
			{Path: "v2-records/web/staging/instance.json", Body: []byte(`{}`)}},
		After: []files.TreeFile{{Path: "v2-records/teams.json", Body: []byte(`{"teams":{}}`)},
			{Path: "v2-records/web/staging/instance.json", Body: []byte(`{"changed":true}`)},
			{Path: "platform/notify/channels/channel-payments.sops.yaml", Body: []byte("ENC[\n")}}}
	publisher := githubtest.NewPublisher(githubtest.PublisherScenario())
	lines := []string{}
	got, err := orchestration.Publish(context.Background(), inputs, publisher, func(line string) {
		lines = append(lines, line)
	})
	if err != nil {
		t.Fatal(err)
	}
	if strings.Join(got.Paths, ",") != "platform/notify/channels/channel-payments.sops.yaml,v2-records/teams.json" {
		t.Fatalf("paths = %v", got.Paths)
	}
	want := []string{"A platform/notify/channels/channel-payments.sops.yaml", "M v2-records/teams.json",
		"Merge plan: you merge it on GitHub; it needs Secret values to be set on the pull request branch",
		"Committed 3333333 [console] teams: set the notification channel of payments",
		"Creating branch console/team-channel-set-payments-0123456",
		"Opened " + githubtest.PublisherScenario().PullURL}
	if strings.Join(lines, "\n") != strings.Join(want, "\n") {
		t.Errorf("lines:\n%s\nwant:\n%s", strings.Join(lines, "\n"), strings.Join(want, "\n"))
	}
	if pull := publisher.Pulls[0]; !strings.Contains(pull.Body, "**Merge plan:** it needs Secret values") {
		t.Errorf("the pull request's body names no merge plan: %q", pull.Body)
	}
}

// A branch name the kind cannot read back is refused before GitHub is written.
func TestPublishRefusesAnImpossibleBranch(t *testing.T) {
	inputs, publisher, _ := published(t)
	inputs.Name = "Web"
	if _, err := orchestration.Publish(context.Background(), inputs, publisher, func(string) {}); err == nil {
		t.Error("a name that is not a DNS label was published")
	}
	if len(publisher.Blobs) != 0 {
		t.Error("an impossible branch wrote to GitHub")
	}
}

// A new app's pull request says what made the repository before it names the commands, and that sentence is the same in
// the commit it carries.
func TestPublishPreface(t *testing.T) {
	inputs, publisher, _ := published(t)
	change, _ := pages.ConsoleChangeNamed("v2-scale")
	inputs.Change = change
	inputs.Preface = "The console created https://github.com/owner/web from [the template](https://github.com/owner/t) " +
		"and waited for its first image.\n\n"
	if _, err := orchestration.Publish(context.Background(), inputs, publisher, func(string) {}); err != nil {
		t.Fatal(err)
	}
	if !strings.HasPrefix(publisher.Pulls[0].Body, inputs.Preface+"Generated by the console with:\n\n    ") {
		t.Errorf("the pull request's body is:\n%s", publisher.Pulls[0].Body)
	}
	if !strings.Contains(publisher.Commits[0].Message, "\n\n"+inputs.Preface+"Generated by the console with:") {
		t.Errorf("the commit message is:\n%s", publisher.Commits[0].Message)
	}
}
